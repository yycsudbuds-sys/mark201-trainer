#!/usr/bin/env python3
"""Bundle content/fin201/ch*.json into app/courses/fin201/data.js with every id prefixed "fin201-".

Usage: python tools/build_fin201.py        (run tools/validate_fin201.py NN for each chapter first;
                                            run tools/build.py afterwards so sw.js gets the new version)
"""
import glob
import hashlib
import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from build import prefix_ids  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
COURSE = "fin201"
CHAPTER_META = {
    8: {"color": "#2E6F8E", "short": "Stocks", "tag": "Value a share", "province": "Illyricum", "numeral": "VIII"},
    9: {"color": "#8A2A1E", "short": "Decision rules", "tag": "NPV, IRR and friends", "province": "Pannonia", "numeral": "IX"},
    10: {"color": "#B5623A", "short": "Cash flows", "tag": "What counts, CCA and salvage", "province": "Dacia", "numeral": "X"},
    11: {"color": "#4F6A3F", "short": "Project analysis", "tag": "What-ifs and real options", "province": "Thracia", "numeral": "XI"},
    12: {"color": "#7A4A1E", "short": "Risk & return", "tag": "σ, ρ and diversification", "province": "Cappadocia", "numeral": "XII"},
    13: {"color": "#2F8F8A", "short": "CAPM", "tag": "β, the SML and the market line", "province": "Syria", "numeral": "XIII"},
}


def prefix_formulas(ch, course):
    p = course + "-"
    for f in ch.get("formulas", []):
        if not f["id"].startswith(p):
            f["id"] = p + f["id"]
        f["concepts"] = [c if c.startswith(p) else p + c for c in f.get("concepts", [])]
    return ch


def main():
    src = os.path.join(ROOT, "content", COURSE)
    chapters = []
    for f in sorted(glob.glob(os.path.join(src, "ch*.json"))):
        with open(f, encoding="utf-8") as fh:
            ch = json.load(fh)
        ch.update(CHAPTER_META.get(ch["chapter"], {"color": "#94A3B8", "short": f"Ch {ch['chapter']}", "tag": ""}))
        chapters.append(prefix_formulas(prefix_ids(ch, COURSE), COURSE))
    chapters.sort(key=lambda c: c["chapter"])
    total_q = sum(len(c["questions"]) for c in chapters)
    total_c = sum(len(c["concepts"]) for c in chapters)
    total_a = sum(len(c.get("activities", [])) for c in chapters)
    numeric = sum(1 for c in chapters for q in c["questions"] if q.get("type") in ("numeric", "multistep"))
    payload = {"course": COURSE, "chapters": chapters, "stats": {"questions": total_q, "concepts": total_c, "activities": total_a, "numeric": numeric}}
    text = json.dumps(payload, ensure_ascii=False, separators=(",", ":"))
    payload["version"] = hashlib.sha1(text.encode("utf-8")).hexdigest()[:10]
    text = json.dumps(payload, ensure_ascii=False, separators=(",", ":"))
    out = os.path.join(ROOT, "app", "courses", COURSE, "data.js")
    os.makedirs(os.path.dirname(out), exist_ok=True)
    with open(out, "w", encoding="utf-8") as fh:
        fh.write("// Generated by tools/build_fin201.py — do not edit by hand. Ids are prefixed with the course id.\n")
        fh.write("export const CONTENT = ")
        fh.write(text)
        fh.write(";\n")
    print(f"Bundled {len(chapters)} chapters: {total_c} concepts, {total_q} questions ({numeric} numeric), {total_a} activities -> app/courses/{COURSE}/data.js (v{payload['version']}, {len(text)//1024} KB)")


if __name__ == "__main__":
    main()
