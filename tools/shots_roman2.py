import os
import sys
from playwright.sync_api import sync_playwright

BASE = sys.argv[1] if len(sys.argv) > 1 else "http://127.0.0.1:8791/"
SH = sys.argv[2] if len(sys.argv) > 2 else os.path.join(os.path.dirname(__file__), "shots_roman")
os.makedirs(SH, exist_ok=True)
errs = []
with sync_playwright() as p:
    b = p.chromium.launch(args=["--disable-gpu"])
    pg = b.new_context(viewport={"width": 1280, "height": 900}).new_page()
    pg.on("pageerror", lambda e: errs.append(str(e)))
    pg.goto(BASE, wait_until="load")
    pg.wait_for_selector("input[type=text]")
    pg.fill("input[type=text]", "Austin")
    pg.click("text=Join the legion")
    pg.wait_for_selector(".hq")
    pg.goto(BASE + "#/campaign/6/t06-2/read", wait_until="load")
    pg.wait_for_selector(".cutscene.show")
    pg.wait_for_timeout(2500)
    pg.screenshot(path=os.path.join(SH, "04b_briefing.png"))
    pg.click("text=Skip briefing")
    pg.wait_for_timeout(300)
    pg.goto(BASE + "#/drill", wait_until="load")
    pg.wait_for_timeout(200)
    pg.click("text=March out")
    pg.wait_for_selector(".cutscene.show")
    pg.wait_for_timeout(200)
    pg.click("text=Skip briefing")
    pg.wait_for_selector(".qcard")
    pg.wait_for_timeout(1000)
    pg.screenshot(path=os.path.join(SH, "07b_battle_q.png"))
    pg.evaluate("document.querySelector('.battlefield').advance()")
    pg.wait_for_timeout(100)
    print("adv after advance():", pg.evaluate("document.querySelector('.battlefield').style.getPropertyValue('--adv')"))
    pg.locator(".option").first.click()
    pg.wait_for_timeout(500)
    pg.screenshot(path=os.path.join(SH, "08b_battle_answered.png"))
    pg.evaluate("() => { const a = window.__app; a.state.settings.theme='light'; a.store.flush(); a.applySettings(); }")
    pg.goto(BASE + "#/campaign", wait_until="load")
    pg.wait_for_timeout(900)
    pg.screenshot(path=os.path.join(SH, "02b_map_day.png"))
    pg.goto(BASE + "#/home", wait_until="load")
    pg.wait_for_timeout(900)
    pg.screenshot(path=os.path.join(SH, "01b_castra_day.png"))
    m = b.new_context(viewport={"width": 390, "height": 844}, device_scale_factor=2).new_page()
    m.goto(BASE + "#/campaign/1/t01-1/drill", wait_until="load")
    m.wait_for_timeout(300)
    if m.locator("input[type=text]").count():
        m.fill("input[type=text]", "M")
        m.click("text=Join the legion")
        m.wait_for_timeout(300)
        m.goto(BASE + "#/campaign/1/t01-1/drill", wait_until="load")
    m.wait_for_selector(".cutscene.show")
    m.wait_for_timeout(1500)
    m.screenshot(path=os.path.join(SH, "15b_m_briefing.png"))
    m.click("text=Skip briefing")
    m.wait_for_selector(".qcard")
    m.wait_for_timeout(800)
    m.screenshot(path=os.path.join(SH, "16b_m_battle.png"))
    b.close()
print("ERRORS:", errs or "none")
