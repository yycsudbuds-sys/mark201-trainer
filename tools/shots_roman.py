import os
import sys
from playwright.sync_api import sync_playwright

BASE = sys.argv[1] if len(sys.argv) > 1 else "http://127.0.0.1:8791/"
SH = sys.argv[2] if len(sys.argv) > 2 else os.path.join(os.path.dirname(__file__), "shots_roman")
os.makedirs(SH, exist_ok=True)
errs = []
with sync_playwright() as p:
    b = p.chromium.launch(args=["--disable-gpu"])
    ctx = b.new_context(viewport={"width": 1280, "height": 900})
    pg = ctx.new_page()
    pg.on("console", lambda m: errs.append(m.text) if m.type == "error" else None)
    pg.on("pageerror", lambda e: errs.append(str(e)))
    pg.goto(BASE, wait_until="load")
    pg.wait_for_selector("input[type=text]")
    pg.screenshot(path=os.path.join(SH, "00_enlist.png"))
    pg.fill("input[type=text]", "Austin")
    pg.click("text=Join the legion")
    pg.wait_for_selector(".hq")
    pg.evaluate("""() => { const a = window.__app; const st = a.state; const ch1 = a.index.chapter.get(1); ch1.topics.forEach(t => st.campaign.topics[t.id] = {cleared: Date.now()}); st.campaign.bosses[1] = {cleared: Date.now(), best: 0.95}; const ch6 = a.index.chapter.get(6); st.campaign.topics[ch6.topics[0].id] = {cleared: Date.now()}; a.store.flush(); }""")
    pg.goto(BASE + "#/home", wait_until="load"); pg.wait_for_timeout(1200)
    pg.screenshot(path=os.path.join(SH, "01_castra.png"), full_page=True)
    pg.goto(BASE + "#/campaign", wait_until="load"); pg.wait_for_timeout(1200)
    pg.screenshot(path=os.path.join(SH, "02_map.png"), full_page=False)
    pg.goto(BASE + "#/campaign/6", wait_until="load"); pg.wait_for_timeout(1000)
    pg.screenshot(path=os.path.join(SH, "03_province.png"), full_page=False)
    # cutscene before lesson
    pg.goto(BASE + "#/campaign/6/t06-2/read", wait_until="load"); pg.wait_for_selector(".cutscene.show"); pg.wait_for_timeout(2200)
    pg.screenshot(path=os.path.join(SH, "04_briefing.png"), full_page=False)
    pg.click("text=Skip briefing"); pg.wait_for_selector(".lesson"); pg.wait_for_timeout(800)
    pg.screenshot(path=os.path.join(SH, "05_scroll.png"), full_page=False)
    # drill with battlefield
    pg.goto(BASE + "#/drill", wait_until="load"); pg.wait_for_timeout(300)
    pg.screenshot(path=os.path.join(SH, "06_drill_orders.png"), full_page=False)
    pg.click("text=March out"); pg.wait_for_selector(".cutscene.show"); pg.wait_for_timeout(300)
    pg.click("text=Skip briefing"); pg.wait_for_selector(".qcard"); pg.wait_for_timeout(1200)
    pg.screenshot(path=os.path.join(SH, "07_battle_q.png"), full_page=False)
    pg.locator(".option").first.click(); pg.wait_for_timeout(450)
    pg.screenshot(path=os.path.join(SH, "08_battle_answered.png"), full_page=False)
    for _ in range(4):
        pg.locator(".runner-foot .btn.primary").first.click(); pg.wait_for_timeout(150)
        pg.locator(".option:not([disabled])").first.click(); pg.wait_for_timeout(250)
    pg.screenshot(path=os.path.join(SH, "09_battle_later.png"), full_page=False)
    print("battlefield adv:", pg.evaluate("getComputedStyle(document.querySelector('.battlefield')).getPropertyValue('--adv')"))
    pg.goto(BASE + "#/arcade", wait_until="load"); pg.wait_for_timeout(500)
    pg.screenshot(path=os.path.join(SH, "10_arena.png"), full_page=False)
    pg.goto(BASE + "#/progress", wait_until="load"); pg.wait_for_timeout(600)
    pg.screenshot(path=os.path.join(SH, "11_senate.png"), full_page=True)
    pg.goto(BASE + "#/exam", wait_until="load"); pg.wait_for_timeout(400)
    pg.screenshot(path=os.path.join(SH, "12_great_battle.png"), full_page=False)
    pg.goto(BASE + "#/arcade/flash", wait_until="load"); pg.wait_for_timeout(300); pg.click("text=Start deck"); pg.wait_for_selector(".flash"); pg.wait_for_timeout(500)
    pg.screenshot(path=os.path.join(SH, "13_scrolls.png"), full_page=False)
    print("battlefield removed after leaving quiz:", pg.evaluate("document.querySelectorAll('.battlefield').length"))
    m = b.new_context(viewport={"width": 390, "height": 844}, device_scale_factor=2).new_page()
    m.on("pageerror", lambda e: errs.append("mobile " + str(e)))
    m.goto(BASE + "#/campaign", wait_until="load"); m.wait_for_timeout(300)
    if m.locator("input[type=text]").count():
        m.fill("input[type=text]", "M"); m.click("text=Join the legion"); m.wait_for_timeout(300); m.goto(BASE + "#/campaign", wait_until="load"); m.wait_for_timeout(800)
    m.screenshot(path=os.path.join(SH, "14_m_map.png"), full_page=True)
    m.goto(BASE + "#/campaign/1/t01-1/drill", wait_until="load"); m.wait_for_selector(".cutscene.show"); m.wait_for_timeout(1500)
    m.screenshot(path=os.path.join(SH, "15_m_briefing.png"), full_page=False)
    m.click("text=Skip briefing"); m.wait_for_selector(".qcard"); m.wait_for_timeout(800)
    m.screenshot(path=os.path.join(SH, "16_m_battle.png"), full_page=False)
    print("mobile overflow:", m.evaluate("document.documentElement.scrollWidth > document.documentElement.clientWidth + 1"))
    b.close()
print("ERRORS:", errs or "none")
