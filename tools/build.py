#!/usr/bin/env python3
"""Bundle content/ch*.json into app/courses/mark201/data.js (an ES module) for the static site.

Every concept, topic, question and activity id is prefixed with the course id ("mark201-") at bundle time so no two
course packs can ever share an id. The source files under content/ are left exactly as they are.

Usage: python tools/build.py
"""
import glob
import json
import os
import hashlib

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CHAPTER_META = {
    1: {"color": "#D4A834", "short": "Marketing", "emoji": "🏛️", "tag": "Why marketing exists", "province": "Italia", "numeral": "I"},
    6: {"color": "#C8683A", "short": "STP", "emoji": "🎯", "tag": "Segment, target, position", "province": "Hispania", "numeral": "VI"},
    7: {"color": "#8FAA5A", "short": "Products", "emoji": "🏺", "tag": "Products, brands, services", "province": "Gallia", "numeral": "VII"},
    8: {"color": "#6FA0B8", "short": "New products", "emoji": "⚔️", "tag": "Life cycles and launches", "province": "Britannia", "numeral": "VIII"},
    9: {"color": "#B08968", "short": "Pricing", "emoji": "🪙", "tag": "Capture the value", "province": "Germania", "numeral": "IX"},
    10: {"color": "#A98BC9", "short": "Channels", "emoji": "⛵", "tag": "Channels and supply chains", "province": "Graecia", "numeral": "X"},
    11: {"color": "#D28C3C", "short": "Retail", "emoji": "🏪", "tag": "Retailing and wholesaling", "province": "Asia", "numeral": "XI"},
    12: {"color": "#4FA3A5", "short": "IMC", "emoji": "📯", "tag": "Integrated communications", "province": "Aegyptus", "numeral": "XII"},
}


COURSE = "mark201"


def prefix_ids(ch, course):
    """Prefix every id and every id reference in a chapter with the course id (idempotent)."""
    p = course + "-"
    px = lambda v: v if (not isinstance(v, str) or v.startswith(p)) else p + v
    for t in ch.get("topics", []):
        t["id"] = px(t["id"])
        t["concepts"] = [px(c) for c in t.get("concepts", [])]
    for c in ch.get("concepts", []):
        c["id"] = px(c["id"])
        if c.get("topic"):
            c["topic"] = px(c["topic"])
    for q in ch.get("questions", []):
        q["id"] = px(q["id"])
        q["concept"] = px(q["concept"])
        if q.get("also"):
            q["also"] = [px(c) for c in q["also"]]
    for a in ch.get("activities", []):
        a["id"] = px(a["id"])
        if a.get("concept"):
            a["concept"] = px(a["concept"])
        if a.get("concepts"):
            a["concepts"] = [px(c) for c in a["concepts"]]
    return ch


def main():
    import sys
    src = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, "content")
    chapters = []
    files = sorted(glob.glob(os.path.join(src, "ch*.json")))
    for f in files:
        with open(f, encoding="utf-8") as fh:
            ch = json.load(fh)
        meta = CHAPTER_META.get(ch["chapter"], {"color": "#94A3B8", "short": f"Ch {ch['chapter']}", "emoji": "📘", "tag": ""})
        ch.update(meta)
        chapters.append(prefix_ids(ch, COURSE))
    chapters.sort(key=lambda c: c["chapter"])
    total_q = sum(len(c["questions"]) for c in chapters)
    total_c = sum(len(c["concepts"]) for c in chapters)
    total_a = sum(len(c["activities"]) for c in chapters)
    payload = {
        "course": COURSE,
        "chapters": chapters,
        "stats": {"questions": total_q, "concepts": total_c, "activities": total_a},
    }
    text = json.dumps(payload, ensure_ascii=False, separators=(",", ":"))
    hasher = hashlib.sha1(text.encode("utf-8"))
    for f in sorted(glob.glob(os.path.join(ROOT, "app", "**", "*.*"), recursive=True)) + [os.path.join(ROOT, "index.html")]:
        if f.endswith("data.js"):
            continue
        with open(f, "rb") as fh:
            hasher.update(fh.read())
    digest = hasher.hexdigest()[:10]
    payload["version"] = digest
    text = json.dumps(payload, ensure_ascii=False, separators=(",", ":"))
    out = os.path.join(ROOT, "app", "courses", COURSE, "data.js")
    os.makedirs(os.path.dirname(out), exist_ok=True)
    with open(out, "w", encoding="utf-8") as fh:
        fh.write("// Generated by tools/build.py — do not edit by hand.\n")
        fh.write("export const CONTENT = ")
        fh.write(text)
        fh.write(";\n")
    sw = os.path.join(ROOT, "sw.js")
    if os.path.exists(sw):
        with open(sw, encoding="utf-8") as fh:
            swt = fh.read()
        import re as _re
        swt = _re.sub(r"const VERSION = '[^']*';", f"const VERSION = '{digest}';", swt)
        with open(sw, "w", encoding="utf-8") as fh:
            fh.write(swt)
    print(f"Bundled {len(chapters)} chapters: {total_c} concepts, {total_q} questions, {total_a} activities -> app/courses/{COURSE}/data.js (v{digest}, {len(text)//1024} KB)")


if __name__ == "__main__":
    main()
