#!/usr/bin/env python3
"""Bundle content/ch*.json into app/data.js (an ES module) for the static site.

Usage: python tools/build.py
"""
import glob
import json
import os
import hashlib

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CHAPTER_META = {
    1: {"color": "#FF6B6B", "short": "Marketing", "emoji": "🧭", "tag": "Why marketing exists"},
    6: {"color": "#FFB84D", "short": "STP", "emoji": "🎯", "tag": "Segment, target, position"},
    7: {"color": "#A3E635", "short": "Products", "emoji": "📦", "tag": "Products, brands, services"},
    8: {"color": "#2DD4BF", "short": "New products", "emoji": "🚀", "tag": "Life cycles and launches"},
    9: {"color": "#38BDF8", "short": "Pricing", "emoji": "🏷️", "tag": "Capture the value"},
    10: {"color": "#A78BFA", "short": "Channels", "emoji": "🚚", "tag": "Channels and supply chains"},
    11: {"color": "#F472B6", "short": "Retail", "emoji": "🛒", "tag": "Retailing and wholesaling"},
    12: {"color": "#FB923C", "short": "IMC", "emoji": "📣", "tag": "Integrated communications"},
}


def main():
    import sys
    src = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, "content")
    chapters = []
    files = sorted(glob.glob(os.path.join(src, "ch*.json")))
    for f in files:
        with open(f, encoding="utf-8") as fh:
            ch = json.load(fh)
        meta = CHAPTER_META.get(ch["chapter"], {"color": "#94A3B8", "short": f"Ch {ch['chapter']}", "emoji": "📘", "tag": ""})
        ch.update(meta)
        chapters.append(ch)
    chapters.sort(key=lambda c: c["chapter"])
    total_q = sum(len(c["questions"]) for c in chapters)
    total_c = sum(len(c["concepts"]) for c in chapters)
    total_a = sum(len(c["activities"]) for c in chapters)
    payload = {
        "chapters": chapters,
        "stats": {"questions": total_q, "concepts": total_c, "activities": total_a},
    }
    text = json.dumps(payload, ensure_ascii=False, separators=(",", ":"))
    hasher = hashlib.sha1(text.encode("utf-8"))
    for f in sorted(glob.glob(os.path.join(ROOT, "app", "**", "*.*"), recursive=True)) + [os.path.join(ROOT, "index.html")]:
        if f.endswith("data.js"):
            continue
        with open(f, "rb") as fh:
            hasher.update(fh.read())
    digest = hasher.hexdigest()[:10]
    payload["version"] = digest
    text = json.dumps(payload, ensure_ascii=False, separators=(",", ":"))
    out = os.path.join(ROOT, "app", "data.js")
    with open(out, "w", encoding="utf-8") as fh:
        fh.write("// Generated by tools/build.py — do not edit by hand.\n")
        fh.write("export const CONTENT = ")
        fh.write(text)
        fh.write(";\n")
    sw = os.path.join(ROOT, "sw.js")
    if os.path.exists(sw):
        with open(sw, encoding="utf-8") as fh:
            swt = fh.read()
        import re as _re
        swt = _re.sub(r"const VERSION = '[^']*';", f"const VERSION = '{digest}';", swt)
        with open(sw, "w", encoding="utf-8") as fh:
            fh.write(swt)
    print(f"Bundled {len(chapters)} chapters: {total_c} concepts, {total_q} questions, {total_a} activities -> app/data.js (v{digest}, {len(text)//1024} KB)")


if __name__ == "__main__":
    main()
